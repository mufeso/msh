package app

import (
	"fmt"
	"strings"

	"example.com/msh/internal/exitcode"
)

// section is one command in the reference documentation.
type section struct {
	title string
	usage string
}

// referenceSections returns the usage of every command and subcommand.
func referenceSections() []section {
	out := []section{}
	seen := map[string]bool{}
	sub := map[string][]section{
		"config": {
			{"config init", configInitUsage}, {"config show", configShowUsage}, {"config validate", configValidateUsage},
		},
		"history": {
			{"history list", historyListUsage}, {"history show", historyShowUsage},
			{"history diff", historyDiffUsage}, {"history prune", historyPruneUsage},
		},
		"hosts": {{"hosts list", hostsListUsage}, {"hosts check", hostsCheckUsage}},
		"packages": {
			{"packages list", packagesListUsage}, {"packages check", packagesCheckUsage}, {"packages find", packagesFindUsage},
			{"packages compare", packagesCompareUsage}, {"packages updates", packagesUpdatesUsage},
		},
		"runbook": {{"runbook list", runbookListUsage}, {"runbook show", runbookShowUsage}, {"runbook run", runbookRunUsage}},
		"task":    {{"task list", taskListUsage}, {"task show", taskShowUsage}, {"task run", taskRunUsage}},
	}
	for _, cmd := range commands() {
		if cmd.hidden || seen[cmd.name] {
			continue
		}
		seen[cmd.name] = true
		out = append(out, section{cmd.name, cmd.usage})
		out = append(out, sub[cmd.name]...)
	}
	return out
}

// roffEscape protects text for man pages.
func roffEscape(s string) string {
	s = strings.ReplaceAll(s, `\`, `\e`)
	s = strings.ReplaceAll(s, "-", `\-`)
	var lines []string
	for _, line := range strings.Split(s, "\n") {
		if strings.HasPrefix(line, ".") || strings.HasPrefix(line, "'") {
			line = `\&` + line
		}
		lines = append(lines, line)
	}
	return strings.Join(lines, "\n")
}

// Manual returns the man page.
func Manual() string {
	var b strings.Builder
	b.WriteString(".\\\" Generated by cmd/msh-docs. Do not edit.\n")
	b.WriteString(".TH MSH 1 \"\" \"msh\" \"User Commands\"\n")
	b.WriteString(".SH NAME\nmsh \\- My Parallel SSH, an SSH fleet-management tool for Linux servers\n")
	b.WriteString(".SH SYNOPSIS\n.B msh\n.I command\n[flags]\n")
	b.WriteString(".SH DESCRIPTION\nmsh runs commands, tasks, scripts and runbooks on one or many servers over SSH, ")
	b.WriteString("sequentially or in parallel, directly or through a bastion, with verified host keys.\n")
	b.WriteString(".SH COMMANDS\n")
	for _, s := range referenceSections() {
		fmt.Fprintf(&b, ".SS %s\n.nf\n%s\n.fi\n", roffEscape(s.title), strings.TrimRight(roffEscape(s.usage), "\n"))
	}
	b.WriteString(".SH SHORTCUTS\nRead-only commands with the same selection flags as exec:\n.nf\n")
	b.WriteString(strings.TrimRight(roffEscape(shortcutsHelp()), "\n"))
	b.WriteString("\n.fi\n.SH EXIT STATUS\n")
	for _, d := range exitcode.All() {
		fmt.Fprintf(&b, ".TP\n.B %d\n%s\n", int(d.Code), roffEscape(d.Meaning))
	}
	b.WriteString(".SH FILES\n.TP\n~/.config/msh/config.yaml\nconfiguration, tasks and runbooks\n")
	b.WriteString(".TP\n~/.config/msh/inventory.yaml\nservers, groups and bastions\n")
	b.WriteString(".TP\n~/.local/state/msh\nrun history and runbook progress\n")
	b.WriteString(".TP\n~/.cache/msh\ncached facts\n")
	b.WriteString(".SH SEE ALSO\n.BR ssh (1),\n.BR tmux (1)\n")
	return b.String()
}
